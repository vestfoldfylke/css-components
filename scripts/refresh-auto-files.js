// Kanskje bare lage metadata i en egen js-string også? Putte alt inn i en build mappe? Eller bare en build.js fil?

import { copyFileSync, existsSync, mkdirSync, readFileSync, write, writeFileSync } from 'fs'
import { generateAutoCss, Css } from '../lib/generate-auto-css.js'

// Generate metadata
console.log('- Reading metadata from package.json, and creating css-metadata...')
const metadata = JSON.parse(readFileSync('./package.json', 'utf-8'))

const metadataCss = new Css()
metadataCss.addLine(`/* ${metadata.name} - ${metadata.description} */`)
metadataCss.addLine(`/* VERSION: ${metadata.version} */`)
metadataCss.addLine(`/* License: ${metadata.license} */`)
metadataCss.addLine()

console.log(`✅ Css metadata successfully created - ${metadata.name} - ${metadata.version}`)

// Generate auto css
console.log('- Generating auto-css...')
const autoGeneratedCss = generateAutoCss()
console.log('✅ Auto-css successfully generated')

// Get manual css from components.css
console.log('- Reading manual css from components.css...')
const componentsCss = readFileSync('./lib/components.css', 'utf-8')

const startManualLine = '/* --- START MANUAL CSS --- */'
const startManualIndex = componentsCss.indexOf(startManualLine)
if (startManualIndex === -1) {
  console.log(`! Could not find start of manual-content line, please add the line "${startManualLine}" to components.css where you want the manual css to start`)
  process.exit(1)
}

const manualCss = componentsCss.substring(startManualIndex)
console.log(`✅ Custom css successfully read - length: ${manualCss.length}`)

// Then we write metadata and manual css to js files in string variables to be able to import them in web
const autoGeneratedDir = './lib/auto-generated'
if (!existsSync(autoGeneratedDir)) {
  console.log(`- ${autoGeneratedDir} dir does not exist, creating...`)
  mkdirSync(autoGeneratedDir)
  console.log(`✅ ${autoGeneratedDir} dir successfully created`)
}

console.log(`- Writing metadata.js in ${autoGeneratedDir}...`)
const comment = '// Created by scripts/refresh-auto-files.js, run "npm run refresh" or "node scripts/refresh-auto-files.js" to update - edits here will be overwritten'
const metadataCode = `export const cssMetadata = \`${metadataCss.css}\``
writeFileSync(`${autoGeneratedDir}/metadata.js`, `${comment}\n${metadataCode}`)
console.log('✅ metadata.js successfully created')

console.log(`- Writing custom-css.js in ${autoGeneratedDir}...`)
const manualCssCode = `export const manualCss = \`${manualCss}\``
writeFileSync(`${autoGeneratedDir}/custom-css.js`, `${comment}\n${manualCssCode}`)
console.log('✅ custom-css.js successfully created')

// Merge metadata, auto-generated css and custom css to update components.css for development
// Dev info
const devInfoAutoCss = new Css()
devInfoAutoCss.addLine('/* READ THIS BEFORE EDITING: ')
devInfoAutoCss.addLine('This part is autogenerated, and will be overwritten on next run of "npm run refresh" or "node scripts/refresh-auto-files.js"')
devInfoAutoCss.addLine(`To edit the css, scroll down to or search for "${startManualLine.replace('/*', '').replace('*/', '').trim()}" and edit below that line`)
devInfoAutoCss.addLine('To refresh the auto-generated generateCss files and the autogenerated content in this file, make your changes, and then run "npm run refresh" or "node scripts/refresh-auto-files.js"')
devInfoAutoCss.addLine('*/')
devInfoAutoCss.addLine()

const devInfoManualCss = new Css()
devInfoManualCss.addLine('/* READ THIS BEFORE EDITING THE MANUAL CSS: ')
devInfoManualCss.addLine('This part is the manual css - Here you can manually craft the css for html elements, classes and so on')
devInfoManualCss.addLine('This part (the manual css) will be merged in with the autocss above when refreshing. Run "npm run refresh" or "node scripts/refresh-auto-files.js" to update the components.css file when you have made changes to reflect them in the web app')
devInfoManualCss.addLine('Guidelines:')
devInfoManualCss.addLine('  - Use the variables in the auto-generated css to keep the design consistent')
devInfoManualCss.addLine('  - Comment your css to make it easier to understand and maintain')
devInfoManualCss.addLine('  - Use the same naming conventions as the auto-generated css')
devInfoManualCss.addLine('  - Try to use native html elements')
devInfoManualCss.addLine('*/')
devInfoManualCss.addLine()

const fullCss = devInfoAutoCss.css + metadataCss.css + autoGeneratedCss.css + devInfoManualCss.css + manualCss
console.log('- Overwriting components.css...')
writeFileSync('./lib/components.css', fullCss)
console.log('✅ components.css successfully updated')

// Add generate-auto-css.js to web/scripts
console.log('- Writing generate-auto-css.js in web/scripts dir...')
copyFileSync('./lib/generate-auto-css.js', './web/scripts/DONT_EDIT-generate-auto-css.js')
console.log('✅ auto-generate-css.js successfully created')

console.log('👍 Refresh complete - enjoy developing!')
